<?php
declare(strict_types=1);

require_once __DIR__ . '/config.php';

/**
 * Validates and stores an uploaded image under a random name.
 * Returns [filename, null] on success or [null, error message].
 */
function store_image(array $file, int $maxEdge = MAX_IMAGE_EDGE): array
{
    if (($file['error'] ?? UPLOAD_ERR_NO_FILE) !== UPLOAD_ERR_OK) {
        return [null, 'Upload failed. Please choose an image and try again.'];
    }
    if ($file['size'] > MAX_UPLOAD_BYTES) {
        return [null, 'Image is too large (max 8 MB).'];
    }
    if (!is_uploaded_file($file['tmp_name'])) {
        return [null, 'Invalid upload.'];
    }

    $allowed = ['image/jpeg' => 'jpg', 'image/png' => 'png', 'image/webp' => 'webp'];
    $mime = (new finfo(FILEINFO_MIME_TYPE))->file($file['tmp_name']);
    if (!isset($allowed[$mime]) || @getimagesize($file['tmp_name']) === false) {
        return [null, 'Only JPG, PNG or WebP images are allowed.'];
    }

    if (!is_dir(UPLOAD_DIR)) {
        mkdir(UPLOAD_DIR, 0750, true);
    }

    $name = bin2hex(random_bytes(16)) . '.' . $allowed[$mime];
    $target = UPLOAD_DIR . '/' . $name;

    // Re-encode with GD when available: strips metadata and any embedded payload.
    if (function_exists('imagecreatefromstring')) {
        $image = @imagecreatefromstring((string) file_get_contents($file['tmp_name']));
        if ($image === false) {
            return [null, 'Could not read that image.'];
        }
        $width = imagesx($image);
        $height = imagesy($image);
        $scale = min(1, $maxEdge / max($width, $height));
        if ($scale < 1) {
            $resized = imagescale($image, (int) round($width * $scale), (int) round($height * $scale));
            if ($resized !== false) {
                $image = $resized;
            }
        }
        $ok = match ($mime) {
            'image/png' => imagepng($image, $target, 6),
            'image/webp' => imagewebp($image, $target, 85),
            default => imagejpeg($image, $target, 86),
        };
        if (!$ok) {
            return [null, 'Could not save the image.'];
        }
    } elseif (!move_uploaded_file($file['tmp_name'], $target)) {
        return [null, 'Could not save the image.'];
    }

    chmod($target, 0644);
    return [$name, null];
}

function delete_image(string $filename): void
{
    // Filenames are generated by us; refuse anything that isn't a plain name.
    if (!preg_match('/^[a-f0-9]{32}\.(jpg|png|webp)$/', $filename)) {
        return;
    }
    $path = UPLOAD_DIR . '/' . $filename;
    if (is_file($path)) {
        unlink($path);
    }
}
